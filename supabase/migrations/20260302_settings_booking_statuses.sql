-- Policies
CREATE POLICY "Authenticated users can read booking statuses" ON settings_booking_statuses FOR SELECT USING (auth.role() = 'authenticated');
CREATE POLICY "Admin full access for booking statuses" ON settings_booking_statuses FOR ALL USING (
  EXISTS (
    SELECT 1 FROM user_profiles
    WHERE user_profiles.id = auth.uid()
    AND user_profiles.role = 'admin'
  )
);

-- Add updated_at triggers to settings tables
CREATE OR REPLACE FUNCTION handle_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- settings_airlines
DO $$ BEGIN
  CREATE TRIGGER set_updated_at
  BEFORE UPDATE ON settings_airlines
  FOR EACH ROW EXECUTE PROCEDURE handle_updated_at();
EXCEPTION WHEN OTHERS THEN NULL; END $$;

