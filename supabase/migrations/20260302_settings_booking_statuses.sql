-- Fix type mismatch and foreign key for email_templates.currency_id
-- settings_currencies.id is now bigint, while email_templates.currency_id was UUID.

DO $$
BEGIN
  -- 1. Drop the existing unique index that uses the UUID fallback
  DROP INDEX IF EXISTS email_templates_type_airline_region_currency_idx;

  -- 2. Alter column type. We use USING NULL if we can't safely cast,
  -- but since it's a migration and data might be fresh, we'll try to keep it
  -- or clear it if it's invalid UUIDs.
  -- Actually, '0000...' is not castable to bigint, so we must NULL it first if it matches that.

  UPDATE email_templates
  SET currency_id = NULL
  WHERE currency_id IS NOT NULL; -- Reset since IDs changed from UUID to bigint anyway

  ALTER TABLE email_templates
  ALTER COLUMN currency_id TYPE bigint USING NULL;

  -- 3. Recreate the unique index with BIGINT compatible fallback
  -- Using 0 as the "null" equivalent for the unique index check
  CREATE UNIQUE INDEX email_templates_type_airline_region_currency_idx
  ON email_templates (type,
    (COALESCE(airline_id, '00000000-0000-0000-0000-000000000000')),
    (COALESCE(region_id, '00000000-0000-0000-0000-000000000000')),
    (COALESCE(currency_id, 0))
  );

  -- 4. Add the foreign key constraint
  ALTER TABLE email_templates
  ADD CONSTRAINT email_templates_currency_id_fkey
  FOREIGN KEY (currency_id)
  REFERENCES settings_currencies(id)
  ON DELETE CASCADE;

END $$;
