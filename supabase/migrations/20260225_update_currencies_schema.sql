-- Drop existing table if it exists
DROP TABLE IF EXISTS public.settings_currencies CASCADE;

-- Create settings_currencies table with MSSQL compatible schema
CREATE TABLE public.settings_currencies (
  id bigint PRIMARY KEY, -- Use bigint to match MSSQL numeric IDs
  code text NOT NULL,
  name text,
  symbol text,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

-- Enable RLS
ALTER TABLE public.settings_currencies ENABLE ROW LEVEL SECURITY;

-- Create policy for public read access
CREATE POLICY "Allow public read access" ON public.settings_currencies FOR SELECT USING (true);

-- Drop and recreate the foreign key in bookings if it exists
-- First check if bookings table exists and has a currency_id column
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_name = 'bookings') THEN
    -- Check if column exists
    IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'bookings' AND column_name = 'currency_id') THEN
      -- Drop existing constraint if it exists (might have different name)
      ALTER TABLE public.bookings DROP CONSTRAINT IF EXISTS bookings_currency_id_fkey;
      -- Add new constraint
      ALTER TABLE public.bookings
        ADD CONSTRAINT bookings_currency_id_fkey
        FOREIGN KEY (currency_id)
        REFERENCES public.settings_currencies(id);
    END IF;
  END IF;
END $$;


-- 1. Identify the current maximum ID
-- 2. Alter the column to use identity
-- 3. Sync the sequence with the data

DO $$
DECLARE
    max_id bigint;
BEGIN
    SELECT COALESCE(MAX(id), 0) + 1 INTO max_id FROM public.settings_currencies;

    -- Drop and recreate the column as identity if possible, or just add identity to existing
    -- Since it's a primary key, we might need a more careful approach

    -- Add identity to the existing column
    -- Note: ALTER COLUMN id SET DATA TYPE bigint GENERATED BY DEFAULT AS IDENTITY is not directly supported if column already has data in some PG versions
    -- But we can add it like this:
    ALTER TABLE public.settings_currencies
    ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;

    -- Restart the sequence at max_id
    EXECUTE 'ALTER TABLE public.settings_currencies ALTER COLUMN id RESTART WITH ' || max_id;
END $$;
