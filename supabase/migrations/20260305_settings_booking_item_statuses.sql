-- Booking Item Statuses Management
DROP TABLE IF EXISTS settings_booking_item_statuses CASCADE;

CREATE TABLE settings_booking_item_statuses (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    code TEXT,
    name TEXT,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

-- Enable RLS
ALTER TABLE settings_booking_item_statuses ENABLE ROW LEVEL SECURITY;

-- Policies
CREATE POLICY "Authenticated users can read booking item statuses" ON settings_booking_item_statuses FOR SELECT USING (auth.role() = 'authenticated');
CREATE POLICY "Admin full access for booking item statuses" ON settings_booking_item_statuses FOR ALL USING (
  EXISTS (
    SELECT 1 FROM user_profiles
    WHERE user_profiles.id = auth.uid()
    AND user_profiles.role = 'admin'
  )
);

-- Add updated_at trigger
DO $$ BEGIN
  CREATE TRIGGER set_updated_at
  BEFORE UPDATE ON settings_booking_item_statuses
  FOR EACH ROW EXECUTE PROCEDURE handle_updated_at();
EXCEPTION WHEN OTHERS THEN NULL; END $$;