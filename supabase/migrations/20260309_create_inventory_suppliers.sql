-- Create inventory_suppliers table
-- Combines dbo.Proveedor (supplier entity) + dbo.ProveedorProveedor (supplier codes per airline)
-- Migration date: 2026-03-09

CREATE TABLE IF NOT EXISTS inventory_suppliers (
    id              INTEGER  PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,     -- ProveedorId (from dbo.Proveedor)

    -- From dbo.Proveedor
    cif             TEXT,                     -- CIF (fiscal identification number)

    -- From dbo.ProveedorProveedor
    provider_code   TEXT,                     -- CodigoProveedor (GDS / airline-specific supplier code)
    is_active       BOOLEAN  NOT NULL DEFAULT true,  -- Activo

    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Auto-update updated_at on row changes
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

CREATE TRIGGER inventory_suppliers_updated_at
BEFORE UPDATE ON inventory_suppliers
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Indexes
CREATE INDEX IF NOT EXISTS idx_inventory_suppliers_provider_code ON inventory_suppliers (provider_code);
CREATE INDEX IF NOT EXISTS idx_inventory_suppliers_is_active    ON inventory_suppliers (is_active);

-- RLS
ALTER TABLE inventory_suppliers ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Authenticated users can read inventory_suppliers"
  ON inventory_suppliers FOR SELECT
  USING (auth.role() = 'authenticated');

CREATE POLICY "Admin full access for inventory_suppliers"
  ON inventory_suppliers FOR ALL
  USING (
    EXISTS (
      SELECT 1 FROM user_profiles
      WHERE user_profiles.id = auth.uid()
        AND user_profiles.role = 'admin'
    )
  );

