-- Countries Management
DROP TABLE IF EXISTS settings_countries CASCADE;

CREATE TABLE settings_countries (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    iso_alpha2 TEXT,
    iso_alpha3 TEXT,
    iso_num INTEGER,
    phone_prefix TEXT,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

-- Enable RLS
ALTER TABLE settings_countries ENABLE ROW LEVEL SECURITY;

-- Policies
CREATE POLICY "Public read access for settings_countries" ON settings_countries
  FOR SELECT USING (auth.role() = 'authenticated');

CREATE POLICY "Admin full access for settings_countries" ON settings_countries
  FOR ALL USING (
    EXISTS (
      SELECT 1 FROM user_profiles
      WHERE user_profiles.id = auth.uid()
      AND user_profiles.role = 'admin'
    )
  );

-- Trigger for updated_at
DO $$ BEGIN
  CREATE TRIGGER set_updated_at
  BEFORE UPDATE ON settings_countries
  FOR EACH ROW EXECUTE PROCEDURE handle_updated_at();
EXCEPTION WHEN OTHERS THEN NULL; END $$;

