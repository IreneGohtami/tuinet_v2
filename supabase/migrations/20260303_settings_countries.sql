        AND column_name = 'id'
        AND is_identity = 'YES'
    ) THEN
        ALTER TABLE settings_countries ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;

    -- Sync sequence
    PERFORM setval(pg_get_serial_sequence('settings_countries', 'id'), COALESCE(MAX(id), 0) + 1, false) FROM settings_countries;
